#include <unistd.h>

void	ft_is_negative(int n)
{
	char	_n;
	char	_p;

	_n = 'N';
	_p = 'P';
	if (n < 0)
	{
		write(1, &_n, sizeof(_n));
	}
	else
	{
		write(1, &_p, sizeof(_p));
	}
}
