#include "rush01.h"

void	print_permutation(t_cell **grid, int n)
{
	int		row;
	int		col;
	char	c;

	write(1, "\033[0;32m", 7);
	row = 0;
	while (row < n)
	{
		col = 0;
		while (col < n)
		{
			if (grid[row][col].height == 0)
				c = '.';
			else
				c = grid[row][col].height + '0';
			write(1, &c, 1);
			if (col < n - 1)
				write(1, " ", 1);
			col++;
		}
		write(1, "\n", 1);
		row++;
	}
	write(1, "-----\n", 6);
	write(1, "\033[0m", 4);
}

void	ft_print_grid(t_cell **grid, int n)
{
	int		row;
	int		col;
	char	c;

	row = 0;
	while (row < n)
	{
		col = 0;
		while (col < n)
		{
			c = grid[row][col].height + '0';
			write(1, &c, 1);
			if (col < n - 1)
				write(1, " ", 1);
			col++;
		}
		write(1, "\n", 1);
		row++;
	}
}
